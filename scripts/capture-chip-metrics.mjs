#!/usr/bin/env node
/**
 * Regenerates `src/interMetrics.ts` from the exact font file the page ships.
 *
 *   node scripts/capture-chip-metrics.mjs
 *
 * `graph.ts` is pure: it cannot measure text, so it has to predict how wide the browser will draw a
 * label chip. A single average per character is not accurate enough — Inter's advances span 2.4px
 * to 9.9px at 10px, and one real card wraps at 210.2px inside a 210px row, which no average can
 * separate from a card that ends at 200px. So the advances are captured from the shipped
 * `@fontsource-variable/inter` face rather than assumed, for the same reason the API fixtures are
 * captured: a hand-written number asserts what somebody guessed the font does.
 *
 * Rerun this after upgrading `@fontsource-variable/inter` or changing the chip font size.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as fontkit from 'fontkit'

/** Must stay the file named by the `@font-face` in `src/styles.css`. */
const FONT = fileURLToPath(
  new URL('../node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2', import.meta.url),
)
const OUT = fileURLToPath(new URL('../src/interMetrics.ts', import.meta.url))

/** `.chip` in `src/styles.css`: 10px, and the weight it inherits from `body`. */
const FONT_SIZE = 10

/**
 * Printable ASCII, which is every character GitHub label names use in practice. Anything outside it
 * falls back to the widest advance captured here, which can only over-reserve.
 */
const CHARACTERS = Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => String.fromCodePoint(0x20 + i))

const font = await fontkit.openSync(FONT)
const advance = (text) => (font.layout(text).advanceWidth / font.unitsPerEm) * FONT_SIZE
const round = (value) => Math.round(value * 1000) / 1000

const widths = CHARACTERS.map((character) => [character, round(advance(character))])
const fallback = round(Math.max(...widths.map(([, width]) => width)))

const entries = widths
  .map(([character, width]) => `  ${JSON.stringify(character)}: ${width},`)
  .join('\n')

writeFileSync(
  OUT,
  `// Generated by scripts/capture-chip-metrics.mjs. Do not edit by hand.
//
// Advance width in CSS pixels of each printable ASCII character in the shipped Inter Variable face
// at ${FONT_SIZE}px, the size \`.chip\` renders at. Captured from
// node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2.

/** Widest captured advance. Used for any character outside the captured set, so it over-reserves. */
export const CHIP_FALLBACK_CHAR_WIDTH = ${fallback}

export const CHIP_CHAR_WIDTHS: Readonly<Record<string, number>> = {
${entries}
}
`,
)

console.log(`Wrote ${OUT} (${widths.length} characters, fallback ${fallback}).`)
